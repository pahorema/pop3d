export type MessageKey = keyof typeof it;

const dictionaries: Record<Lang, typeof it> = { it, en };
let current: Lang = "it";

export function detectLanguage(): Lang {
  const stored = localStorage.getItem("pop3d.lang");
  if (stored === "it" || stored === "en") return stored;
  return navigator.language.toLowerCase().startsWith("it") ? "it" : "en";
}

export function setLanguage(lang: Lang): void {
  current = lang;
  localStorage.setItem("pop3d.lang", lang);
  document.documentElement.lang = lang;
}

export function language(): Lang {
  return current;
}

/** Translates a message, filling `{placeholders}` from `values`. */
export function t(key: MessageKey, values?: Record<string, string | number>): string {
  let text: string = dictionaries[current][key] ?? key;
  if (values) for (const name in values) text = text.replace(`{${name}}`, String(values[name]));
  return text;
}

export function formatNumber(value: number, digits = 0): string {
  return value.toLocaleString(current === "it" ? "it-IT" : "en-GB", {
    minimumFractionDigits: digits,
    maximumFractionDigits: digits,
  });
}

/** "350 m", "1,2 km" */
export function formatDistance(metres: number): string {
  if (metres < 1000) return `${formatNumber(Math.round(metres / 10) * 10)} ${t("unit.m")}`;
  return `${formatNumber(metres / 1000, metres < 10_000 ? 1 : 0)} ${t("unit.km")}`;
}
